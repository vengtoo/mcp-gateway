import { writeFileSync } from "fs";
import { resolve } from "path";
import type { GatewayConfig } from "./types";
import { discoverTools, type DiscoveredTool } from "./utils";
import { classifyTool, type TrustLevel } from "./classify";

interface PolicyTool {
  qualifiedName: string;
  server: string;
  description: string;
  trust: TrustLevel;
  inputFields: string[];
}

export async function generatePolicy(
  config: GatewayConfig,
  outputPath: string
): Promise<void> {
  const tools: PolicyTool[] = [];

  for (const [name, cfg] of Object.entries(config.servers)) {
    try {
      const { tools: discovered, transport } = await discoverTools(name, cfg);
      for (const t of discovered) {
        tools.push({
          ...t,
          trust: classifyTool(t.qualifiedName),
        });
      }
      await transport.close();
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : String(err);
      console.error(`[!] Failed to connect to "${name}": ${message}`);
    }
  }

  if (tools.length === 0) {
    console.error("No tools discovered — cannot generate policy.");
    process.exit(1);
  }

  const yaml = buildYAML(tools);
  const dest = resolve(outputPath);
  writeFileSync(dest, yaml, "utf-8");

  const low = tools.filter((t) => t.trust === "low").length;
  const med = tools.filter((t) => t.trust === "medium").length;
  const high = tools.filter((t) => t.trust === "high").length;

  console.log(`Generated trust-classified policy with ${tools.length} tool(s) → ${dest}`);
  console.log(`  LOW: ${low}  MEDIUM: ${med}  HIGH: ${high}`);
  console.log(`\nEdit the file to customize which tools to allow or block.`);
  console.log(`Then start the agent:\n`);
  console.log(`  vengtoo-agent --policy ${outputPath}\n`);

  process.exit(0);
}

// buildYAML emits a Vengtoo native YAML policy file (the format loaded by
// `vengtoo-agent --policy <file>` — see the agent's yamlPolicyFile schema).
// The old Rego output is gone; the agent's YAML engine matches each request on
// resource_id (the qualified tool name) + action "invoke", and only through an
// assignment — so every allowed tool is a policy assigned to the mcp_agents role.
function buildYAML(tools: PolicyTool[]): string {
  const servers = [...new Set(tools.map((t) => t.server))];
  const now = new Date().toISOString();
  const total = tools.length;

  const low = tools.filter((t) => t.trust === "low").sort(byName);
  const medium = tools.filter((t) => t.trust === "medium").sort(byName);
  const high = tools.filter((t) => t.trust === "high").sort(byName);

  const lines: string[] = [];

  lines.push("# Auto-generated by Vengtoo MCP Gateway");
  lines.push(`# ${servers.length} server(s), ${total} tool(s) discovered`);
  lines.push(`# Generated: ${now}`);
  lines.push("#");
  lines.push("# Trust levels:");
  lines.push("#   LOW    — read-only operations, allowed for the mcp_agents role");
  lines.push("#   MEDIUM — write/execute operations, allowed for mcp_agents (review first)");
  lines.push("#   HIGH   — destructive operations, DISABLED (commented out) by default");
  lines.push("#");
  lines.push("# Run with the standalone agent:");
  lines.push("#   vengtoo-agent --policy ./policy.yaml");
  lines.push("#");
  lines.push("# The agent matches each request on resource.id (the qualified tool name,");
  lines.push('# e.g. "github__create_issue") and action "invoke". Point your caller at this');
  lines.push("# agent with resource.id set to the qualified tool name.");
  lines.push("#");
  lines.push("# Before using: replace the mcp_agents member IDs below with your real agent");
  lines.push("# subject identities, and review the MEDIUM tools / uncomment any HIGH tools.");
  lines.push("");
  lines.push('version: "1"');
  lines.push("");
  lines.push("# Agents allowed to call MCP tools — replace with your real agent identities.");
  lines.push("roles:");
  lines.push("  - id: mcp_agents");
  lines.push("    name: MCP Agents");
  lines.push("    members:");
  lines.push('      - entity_type: entity');
  lines.push('        entity_id: "agent:claude"');
  lines.push('      - entity_type: entity');
  lines.push('        entity_id: "agent:cursor"');
  lines.push("");
  lines.push("policies:");

  if (low.length > 0) {
    lines.push("  # ── LOW trust (read-only — allowed for mcp_agents) ───────────");
    for (const t of low) pushPolicy(lines, t, false);
  }

  if (medium.length > 0) {
    lines.push("  # ── MEDIUM trust (write/execute — allowed for mcp_agents; review) ──");
    for (const t of medium) pushPolicy(lines, t, false);
  }

  if (high.length > 0) {
    lines.push("  # ── HIGH trust (destructive — DISABLED; uncomment to allow) ──");
    lines.push("  # DANGER: these are destructive operations. Uncomment and scope to");
    lines.push("  # explicit agents before enabling.");
    for (const t of high) pushPolicy(lines, t, true);
  }

  return lines.join("\n") + "\n";
}

// pushPolicy appends one policy block. When commented is true the whole block is
// emitted as YAML comments (the agent has no runtime "disabled" flag — the only
// way to ship a policy present-but-inactive is to comment it out).
function pushPolicy(lines: string[], t: PolicyTool, commented: boolean): void {
  const warning = toolWarning(t);
  if (warning) lines.push(`  # WARNING: ${warning}`);

  const p = commented ? "  # " : "  ";
  lines.push(`${p}- id: allow-${t.qualifiedName}`);
  lines.push(`${p}  effect: ALLOW`);
  lines.push(`${p}  actions: [invoke]`);
  lines.push(`${p}  resource_id: "${t.qualifiedName}"`);
  if (t.description) lines.push(`${p}  # ${t.description.replace(/\s+/g, " ").trim()}`);
  lines.push(`${p}  assignments:`);
  lines.push(`${p}    - entity_type: role`);
  lines.push(`${p}      entity_id: mcp_agents`);
  lines.push("");
}

function byName(a: PolicyTool, b: PolicyTool): number {
  return a.qualifiedName.localeCompare(b.qualifiedName);
}

function toolWarning(t: PolicyTool): string | null {
  const name = t.qualifiedName.toLowerCase();
  if (/execute/.test(name)) {
    return `${t.qualifiedName} can run destructive operations — review carefully`;
  }
  if (/query/.test(name)) {
    return `${t.qualifiedName} — raw queries can be destructive, consider moving to HIGH`;
  }
  return null;
}
